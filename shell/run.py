#!/usr/bin/env python3
"""Shell side cost of the blind BabyJubJub signature on the Keycard Shell (STM32H573, Cortex-M33 at 250 MHz).

Compiles shell/bjj_shell.c for thumbv8m.main with clang, runs it in Unicorn (Cortex-M33 model), checks every
output against a Python reference and the circomlibjs vector, counts executed instructions and estimates cycles
with a per-class Cortex-M33 timing model. Also gives the ISO 7816 T=1 transfer time of each APDU.

Usage: ./shell.sh [--mhz 250] [--fi-di 18] [--fmax 5000000] [--opt-level O2] [--iters 3]
"""
import argparse
import json
import os
import secrets
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

P = 21888242871839275222246405745257275088548364400416034343698204186575808495617
L = 2736030358979909402780800718157159386076813972158567259200215660948447373041
A_ED, D_ED = 168700, 168696
A_MONT = 168698
B8 = (5299619240641551281634865583518297030282874472190772894086521144482721001553,
      16950150798460657717958625567821834550301663161624707787222815936182638968203)
R256 = 1 << 256


# ---------- reference arithmetic ----------

def inv(a, m=P):
    return pow(a, m - 2, m)


def ed_add(p1, p2):
    x1, y1 = p1
    x2, y2 = p2
    k = D_ED * x1 * x2 * y1 * y2 % P
    x3 = (x1 * y2 + y1 * x2) * inv(1 + k) % P
    y3 = (y1 * y2 - A_ED * x1 * x2) * inv(1 - k) % P
    return x3, y3


def ed_mul(k, pt):
    acc = (0, 1)
    while k:
        if k & 1:
            acc = ed_add(acc, pt)
        pt = ed_add(pt, pt)
        k >>= 1
    return acc


def e2w(pt):
    x, y = pt
    a3 = A_MONT * inv(3) % P
    return ((1 + y) * inv(1 - y) + a3) % P, (1 + y) * inv((1 - y) * x % P) % P


def read_consts(name):
    sections, cur = {}, None
    with open(os.path.join(ROOT, "vectors", name)) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            head = line.split()
            if head[0].isalpha() and len(head) == 2 and head[1].isdigit():
                cur = head[0]
                sections[cur] = []
                continue
            sections[cur].append([int(v, 0) for v in head])
    return sections


def poseidon_ref(inputs, C, M):
    st = [0] + list(inputs)
    for r in range(68):
        st = [(a + C[r * 6 + i]) % P for i, a in enumerate(st)]
        if r < 4 or r >= 64:
            st = [pow(a, 5, P) for a in st]
        else:
            st[0] = pow(st[0], 5, P)
        st = [sum(M[i][j] * st[j] for j in range(6)) % P for i in range(6)]
    return st[0]


def pack(rx, ry, s):
    w = ry | ((1 << 255) if rx > (P - 1) // 2 else 0)
    return w.to_bytes(32, "little") + s.to_bytes(32, "little")


# ---------- constants header ----------

def limbs(v):
    return ", ".join("0x%08xu" % ((v >> (32 * i)) & 0xffffffff) for i in range(8))


def mont(v):
    return v * R256 % P


def write_header(path, ref, opt):
    out = ["/* generated by shell/run.py from vectors/poseidon_t6*.txt, do not edit */", "#include <stdint.h>"]

    def arr(name, vals):
        out.append("static const uint32_t %s[%d][8] = {" % (name, len(vals)))
        out.extend("  {%s}," % limbs(v) for v in vals)
        out.append("};")

    def one(name, v):
        out.append("static const uint32_t %s[8] = {%s};" % (name, limbs(v)))

    one("FP_P", P)
    out.append("#define FP_M0INV 0x%08xu" % ((-pow(P, -1, 1 << 32)) % (1 << 32)))
    one("FP_R2", R256 * R256 % P)
    one("FP_ONE", mont(1))
    one("FP_PM2", P - 2)
    one("FP_A3", mont(A_MONT * inv(3) % P))
    one("FP_HALF", (P - 1) // 2)
    one("L_N", L)
    out.append("#define L_M0INV 0x%08xu" % ((-pow(L, -1, 1 << 32)) % (1 << 32)))
    for k in (2, 4, 8, 16, 32):
        one("L_X%d" % k, k * L)
    one("L_K1R", (1 << 256) % L * R256 % L)
    one("L_K2R", (1 << 512) % L * R256 % L)
    C = [v[0] for v in ref["C"]]
    arr("PREF_C", [mont(v) for v in C])
    M = ref["M"]
    arr("PREF_M", [mont(M[i][j]) for j in range(6) for i in range(6)])  # mix() reads m[j*6+i] as M[i][j]
    arr("POPT_C", [mont(v[0]) for v in opt["C"]])
    arr("POPT_S", [mont(v[0]) for v in opt["S"]])
    arr("POPT_M", [mont(v) for row in opt["M"] for v in row])
    arr("POPT_P", [mont(v) for row in opt["P"] for v in row])
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")


# ---------- build ----------

LINK = """MEMORY { FLASH (rx) : ORIGIN = 0x08000000, LENGTH = 2M
         RAM (rwx) : ORIGIN = 0x20000000, LENGTH = 640K }
SECTIONS { .text : { *(.text*) *(.rodata*) } > FLASH
           .bss (NOLOAD) : { *(.bss*) *(COMMON) *(.data*) } > RAM }
"""


def build(bdir, level):
    os.makedirs(bdir, exist_ok=True)
    with open(os.path.join(bdir, "link.ld"), "w") as f:
        f.write(LINK)
    obj = os.path.join(bdir, "bjj_shell.o")
    elf = os.path.join(bdir, "bjj_shell.elf")
    subprocess.check_call(["clang", "--target=thumbv8m.main-none-eabi", "-mcpu=cortex-m33", "-mthumb",
                           "-mfloat-abi=soft", "-" + level, "-ffreestanding", "-fno-builtin", "-nostdlib",
                           "-ffunction-sections", "-I", bdir, "-c", os.path.join(HERE, "bjj_shell.c"), "-o", obj])
    subprocess.check_call(["ld.lld", "-T", os.path.join(bdir, "link.ld"), "--gc-sections",
                           "-e", "step_challenge", "-u", "step_finish_mod", "-u", "step_finish_int",
                           "-u", "op_w2e", "-u", "op_poseidon", "-u", "op_fp_mul", "-u", "op_inv",
                           obj, "-o", elf])
    return elf


# ---------- emulator with instruction counts ----------

class Machine:
    STOP = 0x0F000000
    RAM = 0x20000000
    RAM_SIZE = 640 * 1024

    def __init__(self, elf):
        from elftools.elf.elffile import ELFFile
        import capstone
        import unicorn as U
        from unicorn import arm_const as A
        self.U, self.A = U, A
        with open(elf, "rb") as f:
            e = ELFFile(f)
            text = e.get_section_by_name(".text")
            self.code = text.data()
            self.base = text["sh_addr"]
            self.sym = {s.name: s["st_value"] for s in e.get_section_by_name(".symtab").iter_symbols() if s.name}
            self.size = {s.name: s["st_size"] for s in e.get_section_by_name(".symtab").iter_symbols() if s.name}
        self.uc = U.Uc(U.UC_ARCH_ARM, U.UC_MODE_THUMB | U.UC_MODE_MCLASS)
        self.uc.ctl_set_cpu_model(A.UC_CPU_ARM_CORTEX_M33)
        self.uc.mem_map(0x08000000, 2 * 1024 * 1024)
        self.uc.mem_write(self.base, self.code)
        self.uc.mem_map(self.STOP, 0x1000)
        self.uc.mem_write(self.STOP, b"\x00\xbf" * 16)
        self.uc.mem_map(self.RAM, self.RAM_SIZE)
        self.md = capstone.Cs(capstone.CS_ARCH_ARM, capstone.CS_MODE_THUMB | capstone.CS_MODE_MCLASS)
        self.ins = {}
        self.io = self.sym["io"]

    def decode(self, addr):
        if addr not in self.ins:
            off = addr - self.base
            i = next(self.md.disasm(self.code[off:off + 4], addr, count=1), None)
            self.ins[addr] = (i.mnemonic, i.size, i.op_str) if i else ("?", 2, "")
        return self.ins[addr]

    def wr(self, field_off, data):
        self.uc.mem_write(self.io + field_off, bytes(data))

    def rd(self, field_off, n):
        return bytes(self.uc.mem_read(self.io + field_off, n))

    def call(self, name):
        counts, taken = {}, {}
        last = [None, 0]

        def hook(uc, addr, size, _):
            counts[addr] = counts.get(addr, 0) + 1
            p = last[0]
            if p is not None and addr != p + last[1]:
                taken[p] = taken.get(p, 0) + 1
            last[0], last[1] = addr, size

        h = self.uc.hook_add(self.U.UC_HOOK_CODE, hook, begin=self.base, end=self.base + len(self.code))
        self.uc.reg_write(self.A.UC_ARM_REG_SP, self.RAM + self.RAM_SIZE)
        self.uc.reg_write(self.A.UC_ARM_REG_LR, self.STOP | 1)
        self.uc.emu_start(self.sym[name] | 1, self.STOP)
        self.uc.hook_del(h)
        # the last instruction (return) is a taken branch
        if last[0] is not None:
            taken[last[0]] = taken.get(last[0], 0) + 1
        for addr in counts:
            self.decode(addr)
        return Cost(counts, taken, self.ins)


LOADS = {"ldr", "ldrb", "ldrh", "ldrsb", "ldrsh", "ldr.w", "ldrb.w", "ldrh.w", "ldrsb.w", "ldrsh.w"}
STORES = {"str", "strb", "strh", "str.w", "strb.w", "strh.w"}
MULS = {"mul", "muls", "mla", "mls", "umull", "smull", "umlal", "smlal", "umaal"}


def cycles_of(mn, op, n_exec, n_taken):
    base = mn.split(".")[0]
    if base in ("b", "bl", "bx", "blx", "cbz", "cbnz") or (base.startswith("b") and len(base) == 3 and base not in ("bic", "bfi", "bfc")):
        return n_exec + 2 * n_taken
    if base in ("udiv", "sdiv"):
        return 6 * n_exec
    if mn in LOADS or base in ("ldr", "ldrb", "ldrh", "ldrsb", "ldrsh"):
        return (2 * n_exec) + (2 * n_taken if "pc" in op.split(",")[0] else 0)
    if base in ("ldrd",):
        return 3 * n_exec
    if base in ("strd",):
        return 2 * n_exec
    if base in ("ldm", "ldmia", "ldmdb", "pop", "stm", "stmia", "stmdb", "push"):
        nreg = op[op.find("{"):].count(",") + 1 if "{" in op else 1
        extra = 2 * n_taken if (base in ("pop", "ldm", "ldmia") and "pc" in op) else 0
        return (1 + nreg) * n_exec + extra
    return n_exec


class Cost:
    def __init__(self, counts, taken, ins):
        self.instr = sum(counts.values())
        self.cyc = 0
        for a, n in counts.items():
            mn, _, op = ins.get(a, ("?", 2, ""))
            self.cyc += cycles_of(mn, op, n, taken.get(a, 0))

    def ms(self, mhz, cpi1=False):
        return (self.instr if cpi1 else self.cyc) / (mhz * 1000.0)


# ---------- ISO 7816 T=1 ----------

F_TABLE = [372, 372, 558, 744, 1116, 1488, 1860, 0, 0, 512, 768, 1024, 1536, 2048, 0, 0]
D_TABLE = [0, 1, 2, 4, 8, 16, 32, 64, 12, 20, 0, 0, 0, 0, 0, 0]


def t1_ms(cmd_data, resp_data, fidi, fmax):
    """SC v2 secured APDU over T=1: one I-block each way (IFSC 254), LRC, 11 etu per character, BGT 22 etu."""
    etu = F_TABLE[fidi >> 4] / (D_TABLE[fidi & 0xf] * fmax)
    cmd = 5 + 5 + cmd_data + 8 + 1          # header, inner header, data, CCM tag, Le
    resp = resp_data + 2 + 8 + 2            # data, inner SW, tag, SW
    chars = (cmd + 4) + (resp + 4)          # NAD PCB LEN ... LRC
    return (chars * 11 + 22) * etu * 1000.0, cmd, resp


# ---------- main ----------

OFF = {"rw": 0, "a_ed": 65, "msg": 129, "s_card": 161, "r_ed": 233, "hm": 297, "c": 329, "s": 361,
       "packed": 393, "opt": 460}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--mhz", type=float, default=250.0)
    ap.add_argument("--fi-di", type=lambda s: int(s, 16), default=0x18, help="TA1 of the card ATR, hex (JCOP4: 18)")
    ap.add_argument("--fmax", type=float, default=5e6, help="card clock chosen by the Shell for that TA1 (Hz)")
    ap.add_argument("--opt-level", default="O2")
    ap.add_argument("--iters", type=int, default=3, help="random signatures checked per mode")
    ap.add_argument("--json", help="write the results to this file")
    a = ap.parse_args()

    ref = read_consts("poseidon_t6.txt")
    opt = read_consts("poseidon_t6_opt.txt")
    Cref = [v[0] for v in ref["C"]]
    Mref = ref["M"]
    vec = json.load(open(os.path.join(ROOT, "vectors", "circomlib_vectors.json")))
    assert poseidon_ref([1, 2, 3, 4, 5], Cref, Mref) == int(vec["poseidon5"]["output"]), "Poseidon reference KAT"

    bdir = os.path.join(ROOT, "build", "shell")
    os.makedirs(bdir, exist_ok=True)
    write_header(os.path.join(bdir, "consts.h"), ref, opt)
    elf = build(bdir, a.opt_level)
    m = Machine(elf)
    io_size = m.size.get("io", 0)
    assert io_size >= OFF["opt"] + 4, "struct io layout changed (%d)" % io_size
    text_size = len(m.code)

    def be(v, n=32):
        return v.to_bytes(n, "big")

    def run_sig(R, A, msg, s_card, integer, use_opt):
        X, Y = e2w(R)
        m.wr(OFF["rw"], b"\x04" + be(X) + be(Y))
        m.wr(OFF["a_ed"], be(A[0]) + be(A[1]))
        m.wr(OFF["msg"], be(msg))
        m.wr(OFF["opt"], (1 if use_opt else 0).to_bytes(4, "little"))
        c1 = m.call("step_challenge")
        hm = int.from_bytes(m.rd(OFF["hm"], 32), "big")
        c = int.from_bytes(m.rd(OFF["c"], 32), "big")
        red = m.rd(OFF["r_ed"], 64)
        assert (int.from_bytes(red[:32], "big"), int.from_bytes(red[32:], "big")) == R, "w2e"
        exp_hm = poseidon_ref([R[0], R[1], A[0], A[1], msg], Cref, Mref)
        assert hm == exp_hm, "poseidon (%s)" % ("opt" if use_opt else "ref")
        assert c == exp_hm % L, "hm mod l"
        if integer:
            m.wr(OFF["s_card"], s_card)
            c2 = m.call("step_finish_int")
        else:
            m.wr(OFF["s_card"], s_card[:32])
            c2 = m.call("step_finish_mod")
        return c1, c2, c, m.rd(OFF["packed"], 64)

    # circomlibjs vector, end to end
    ev = vec["eddsa"]
    R8 = (int(ev["R8"][0]), int(ev["R8"][1]))
    Avec = (int(ev["A"][0]), int(ev["A"][1]))
    for use_opt in (True, False):
        _, _, _, packed = run_sig(R8, Avec, int(ev["msg"]), be(int(ev["S"])), False, use_opt)
        assert packed.hex() == ev["packedSignature"], "packSignature vs circomlibjs"
    print("vecteur circomlibjs : hm, c, conversion et packSignature identiques (Poseidon optimisé et référence)")

    # random signatures, both modes, checked with the circomlib equation S.B8 = R8 + 8c.A
    res = {}
    for integer in (False, True):
        for use_opt in (True, False):
            key = ("integer" if integer else "modulaire") + ("/opt" if use_opt else "/ref")
            costs = []
            for _ in range(a.iters):
                s = secrets.randbelow(L - 1) + 1
                A = ed_mul(s, B8)  # random key: A = s.B8, so the check is S.B8 = R8 + c.A
                r = secrets.randbelow(L - 1) + 1
                R = ed_mul(r, B8)
                msg = secrets.randbelow(P)
                c_exp = poseidon_ref([R[0], R[1], A[0], A[1], msg], Cref, Mref) % L
                S = (r + c_exp * s) % L
                if integer:
                    t = secrets.randbits(320)
                    sp = r + L * t + c_exp * s
                    s_card = be(sp, 72)
                else:
                    s_card = be(S) + bytes(40)
                c1, c2, c, packed = run_sig(R, A, msg, s_card, integer, use_opt)
                assert c == c_exp
                assert packed == pack(R[0], R[1], S), "packed (%s)" % key
                lhs = ed_mul(S, B8)
                rhs = ed_add(R, ed_mul(c, A))
                assert lhs == rhs, "signature equation"
                costs.append((c1, c2))
            res[key] = costs
    print("signatures aléatoires vérifiées : %d par mode (S.B8 = R8 + c.A)" % a.iters)

    # isolated operations
    m.wr(OFF["msg"], be(secrets.randbelow(P)))
    ops = {"multiplication Fp": m.call("op_fp_mul"), "inversion Fp (Fermat)": m.call("op_inv")}
    X, Y = e2w(ed_mul(secrets.randbelow(L - 1) + 1, B8))
    m.wr(OFF["rw"], b"\x04" + be(X) + be(Y))
    ops["conversion Weierstrass→Edwards"] = m.call("op_w2e")
    for use_opt in (True, False):
        m.wr(OFF["opt"], (1 if use_opt else 0).to_bytes(4, "little"))
        ops["Poseidon t=6 " + ("optimisé" if use_opt else "référence")] = m.call("op_poseidon")

    mhz = a.mhz
    print()
    print("Shell : Cortex-M33 à %.0f MHz, clang -%s, code %d o (constantes Poseidon comprises)" % (mhz, a.opt_level, text_size))
    print("%-34s %12s %12s %10s %10s" % ("opération", "instructions", "cycles est.", "ms CPI=1", "ms est."))
    for k, c in ops.items():
        print("%-34s %12d %12d %10.3f %10.3f" % (k, c.instr, c.cyc, c.ms(mhz, True), c.ms(mhz)))
    print()
    print("%-22s %26s %26s" % ("par signature", "après COMMIT (R→c)", "après RESPOND (S, pack)"))
    out = {"mhz": mhz, "ops": {k: [c.instr, c.cyc] for k, c in ops.items()}, "sig": {}}
    for key, costs in res.items():
        c1 = max(costs, key=lambda x: x[0].cyc)[0]
        c2 = max(costs, key=lambda x: x[1].cyc)[1]
        print("%-22s %10d instr %7.3f ms %10d instr %7.3f ms" % (key, c1.instr, c1.ms(mhz), c2.instr, c2.ms(mhz)))
        out["sig"][key] = [c1.instr, c1.cyc, c2.instr, c2.cyc]

    print()
    fidi = a.fi_di
    etu = F_TABLE[fidi >> 4] / (D_TABLE[fidi & 0xf] * a.fmax)
    print("T=1 : TA1=%02X, f=%.2f MHz, etu=%.2f µs, %.1f kbit/s (secure channel v2, une I-block par sens)" %
          (fidi, a.fmax / 1e6, etu * 1e6, 1e-3 / etu))
    apdus = [("COMMIT", 0, 65), ("RESPOND plain", 32, 32), ("RESPOND integer", 32, 72),
             ("RESPOND chain", 32, 32 + 65), ("RESPOND integer-chain", 32, 72 + 65)]
    out["t1"] = {}
    for name, cd, rd in apdus:
        ms, cmd, resp = t1_ms(cd, rd, fidi, a.fmax)
        print("  %-22s commande %3d o, réponse %3d o : %6.2f ms" % (name, cmd, resp, ms))
        out["t1"][name] = ms
    if a.json:
        with open(a.json, "w") as f:
            json.dump(out, f, indent=1)


if __name__ == "__main__":
    main()
